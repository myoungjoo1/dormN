BEGIN;

-- One room per group purchase, or one canonical user pair per DM.
CREATE TABLE public.chat_rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_type VARCHAR(10) NOT NULL,
    post_id BIGINT NULL,
    dm_user_a UUID NULL,
    dm_user_b UUID NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chat_rooms_room_type_ck
        CHECK (room_type IN ('GROUP', 'DM')),
    CONSTRAINT chat_rooms_post_fk
        FOREIGN KEY (post_id) REFERENCES public.posts (id) ON DELETE RESTRICT,
    CONSTRAINT chat_rooms_dm_user_a_fk
        FOREIGN KEY (dm_user_a) REFERENCES public.users (id) ON DELETE RESTRICT,
    CONSTRAINT chat_rooms_dm_user_b_fk
        FOREIGN KEY (dm_user_b) REFERENCES public.users (id) ON DELETE RESTRICT,
    CONSTRAINT chat_rooms_shape_ck
        CHECK (
            (room_type = 'GROUP'
                AND post_id IS NOT NULL
                AND dm_user_a IS NULL
                AND dm_user_b IS NULL)
            OR
            (room_type = 'DM'
                AND post_id IS NULL
                AND dm_user_a IS NOT NULL
                AND dm_user_b IS NOT NULL
                AND dm_user_a < dm_user_b)
        )
);

CREATE UNIQUE INDEX chat_rooms_group_post_uq
    ON public.chat_rooms (post_id)
    WHERE room_type = 'GROUP';

CREATE UNIQUE INDEX chat_rooms_dm_pair_uq
    ON public.chat_rooms (dm_user_a, dm_user_b)
    WHERE room_type = 'DM';

-- MVP: this table stores DM members only. GROUP access is derived by FastAPI
-- from posts.author_id and participations.user_id.
CREATE TABLE public.chat_room_members (
    room_id BIGINT NOT NULL,
    user_id UUID NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (room_id, user_id),
    CONSTRAINT chat_room_members_room_fk
        FOREIGN KEY (room_id) REFERENCES public.chat_rooms (id) ON DELETE CASCADE,
    CONSTRAINT chat_room_members_user_fk
        FOREIGN KEY (user_id) REFERENCES public.users (id) ON DELETE RESTRICT
);

CREATE INDEX chat_room_members_user_idx
    ON public.chat_room_members (user_id, room_id);

CREATE TABLE public.chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    sender_id UUID NULL,
    message_type VARCHAR(10) NOT NULL,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chat_messages_room_fk
        FOREIGN KEY (room_id) REFERENCES public.chat_rooms (id) ON DELETE CASCADE,
    CONSTRAINT chat_messages_sender_fk
        FOREIGN KEY (sender_id) REFERENCES public.users (id) ON DELETE RESTRICT,
    CONSTRAINT chat_messages_type_ck
        CHECK (message_type IN ('USER', 'SYSTEM')),
    CONSTRAINT chat_messages_body_ck
        CHECK (
            char_length(body) BETWEEN 1 AND 2000
            AND char_length(btrim(body)) >= 1
        ),
    CONSTRAINT chat_messages_sender_ck
        CHECK (
            (message_type = 'USER' AND sender_id IS NOT NULL)
            OR
            (message_type = 'SYSTEM' AND sender_id IS NULL)
        )
);

-- Cursor pagination reads newest messages first without scanning a room's history.
CREATE INDEX chat_messages_room_cursor_idx
    ON public.chat_messages (room_id, id DESC);

-- Group membership is intentionally not synchronized into chat_room_members.
-- DM member correctness (exactly dm_user_a and dm_user_b) is enforced by the
-- future API transaction, not by a trigger or migration function.
COMMENT ON TABLE public.chat_room_members IS
    'MVP DM membership only; GROUP access is checked from posts and participations in FastAPI.';

-- Keep Supabase Data API access closed until explicit, user-scoped policies are designed.
ALTER TABLE public.chat_rooms ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chat_room_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chat_messages ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE
    public.chat_rooms,
    public.chat_room_members,
    public.chat_messages
FROM PUBLIC, anon, authenticated;

COMMIT;
