-- DormN development-only destructive reset.
--
-- Do not run this file against production or a shared database.
-- Before running it:
--   1. Create a pg_dump backup with db/backup.ps1.
--   2. Verify the backup with pg_restore --list <backup-file>.
--   3. Confirm that the database is the DormN development project.
--
-- This migration intentionally does not create or delete rows in auth.users.
-- public.users will be empty after this migration and will be populated after
-- a real Supabase Auth login.

BEGIN;

DO $$
DECLARE
    auth_user_count BIGINT;
    user_count BIGINT;
    post_count BIGINT;
    participation_count BIGINT;
    settlement_count BIGINT;
BEGIN
    SELECT COUNT(*) INTO auth_user_count FROM auth.users;
    SELECT COUNT(*) INTO user_count FROM public.users;
    SELECT COUNT(*) INTO post_count FROM public.posts;
    SELECT COUNT(*) INTO participation_count FROM public.participations;
    SELECT COUNT(*) INTO settlement_count FROM public.settlements;

    IF auth_user_count <> 0
        OR user_count <> 2
        OR post_count <> 1
        OR participation_count <> 1
        OR settlement_count <> 1
    THEN
        RAISE EXCEPTION
            'Refusing reset: expected auth.users=0, users=2, posts=1, participations=1, settlements=1; got auth.users=%, users=%, posts=%, participations=%, settlements=%',
            auth_user_count,
            user_count,
            post_count,
            participation_count,
            settlement_count;
    END IF;
END
$$;

DROP TABLE IF EXISTS public.settlements;
DROP TABLE IF EXISTS public.participations;
DROP TABLE IF EXISTS public.posts;
DROP TABLE IF EXISTS public.users;

CREATE TABLE public.users (
    id UUID PRIMARY KEY
        REFERENCES auth.users(id)
        ON DELETE RESTRICT,

    -- Optional provider subject; the canonical user identity is this UUID.
    kakao_id TEXT UNIQUE,

    room_number VARCHAR(20) UNIQUE,

    dorm_verified BOOLEAN NOT NULL DEFAULT FALSE,

    dorm_verified_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE public.posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    author_id UUID NOT NULL
        REFERENCES public.users(id)
        ON DELETE RESTRICT,

    product_name VARCHAR(200) NOT NULL,

    product_url TEXT,

    image_url TEXT,

    total_price INTEGER NOT NULL
        CHECK (total_price > 0),

    total_quantity INTEGER NOT NULL
        CHECK (total_quantity > 0),

    host_quantity INTEGER NOT NULL
        CHECK (host_quantity >= 1),

    deadline TIMESTAMPTZ NOT NULL,

    pickup_location VARCHAR(200) NOT NULL,

    shortfall_policy VARCHAR(30) NOT NULL
        CHECK (
            shortfall_policy IN (
                'KEEP_BY_HOST',
                'CANCEL_IF_SHORT'
            )
        ),

    status VARCHAR(30) NOT NULL DEFAULT 'RECRUITING'
        CHECK (
            status IN (
                'RECRUITING',
                'CLOSED',
                'ORDERED',
                'ARRIVED',
                'PICKUP',
                'COMPLETED',
                'CANCELLED'
            )
        ),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CHECK (host_quantity <= total_quantity)
);

CREATE TABLE public.participations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    post_id BIGINT NOT NULL
        REFERENCES public.posts(id)
        ON DELETE CASCADE,

    user_id UUID NOT NULL
        REFERENCES public.users(id)
        ON DELETE RESTRICT,

    quantity INTEGER NOT NULL
        CHECK (quantity >= 1),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (post_id, user_id)
);

CREATE TABLE public.settlements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    participation_id BIGINT NOT NULL UNIQUE
        REFERENCES public.participations(id)
        ON DELETE CASCADE,

    amount INTEGER NOT NULL
        CHECK (amount >= 0),

    payment_status VARCHAR(20) NOT NULL DEFAULT 'UNPAID'
        CHECK (
            payment_status IN (
                'UNPAID',
                'SENT',
                'CONFIRMED'
            )
        ),

    sent_at TIMESTAMPTZ,

    confirmed_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMIT;
